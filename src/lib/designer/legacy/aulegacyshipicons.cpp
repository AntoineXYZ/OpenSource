QIcon AuLegacyShipIcon(const QString& originalBaseName)
{
	QString name = originalBaseName.section(QLatin1Char('/'), -1);
	if(name.endsWith(QStringLiteral(".png"))) name.chop(4);
	for(const OriginalIcon& icon : Icons)
		if(name == QLatin1String(icon.name))
		{
			QPixmap pixmap;
			if(pixmap.loadFromData(QByteArray::fromBase64(icon.pngBase64), "PNG"))
				return QIcon(pixmap);
			break;
		}
	return QIcon();
}
